GLYPHS = {char: rows.split("|") for char, rows in _RAW.items()}
FALLBACK = GLYPHS["?"]


def glyph(char: str) -> list[str]:
    return GLYPHS.get(char.upper(), FALLBACK)


def width(text: str) -> int:
    """Width of the text in font pixels (one empty pixel between letters)."""
    if not text:
        return 0
    return sum(len(glyph(c)[0]) for c in text) + len(text) - 1
