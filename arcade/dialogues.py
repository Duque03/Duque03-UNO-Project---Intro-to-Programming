def next_line(name: str, remaining: list[int], rng) -> tuple[tuple[str, str], list[int]]:
    """The next exchange with this bot, and the numbers still to come (all thirty, shuffled, before any repeats)."""
    if not remaining:
        remaining = list(range(len(DIALOGUES[name])))
        rng.shuffle(remaining)
    index, rest = remaining[0], remaining[1:]
    return DIALOGUES[name][index], rest
